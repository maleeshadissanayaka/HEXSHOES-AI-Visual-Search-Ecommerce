import fs from 'node:fs'
import {chromium} from 'playwright'
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'})
try{
 const page=await browser.newPage({viewport:{width:390,height:844}})
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('http://localhost:5173/')
 await page.locator('.prod-card').first().waitFor()
 await page.getByRole('button',{name:'Quick View',exact:true}).first().click()
 await page.getByRole('button',{name:'Add to Cart',exact:true}).click()
 await page.getByRole('button',{name:'Add to wishlist',exact:true}).click()
 await page.keyboard.press('Tab')
 const focusTrapped=await page.evaluate(()=>!!document.activeElement?.closest('[role="dialog"]'))
 await page.keyboard.press('Escape')
 const restoredFocus=await page.evaluate(()=>document.activeElement?.textContent==='Quick View')
 const cart=await page.locator('.cart-pill').innerText(),wishlist=await page.locator('.wish-count').innerText()
 await page.getByRole('button',{name:'HEX Assistant',exact:true}).click()
 await page.getByText('PROTOTYPE',{exact:false}).waitFor()
 await page.getByRole('button',{name:'HEX Assistant',exact:true}).click()
 await page.locator('#file-input').setInputFiles({name:'large.png',mimeType:'image/png',buffer:Buffer.alloc(10*1024*1024+1)})
 await page.getByRole('alert').filter({hasText:'smaller than 10 MB'}).waitFor()
 const bytes=fs.readFileSync('../ai-service/test_query.jpg').toString('base64')
 const response=page.waitForResponse(r=>r.url()==='http://127.0.0.1:8000/search',{timeout:120000})
 await page.locator('.drop-zone').evaluate((zone,bytes)=>{const data=new DataTransfer();data.items.add(new File([Uint8Array.from(atob(bytes),c=>c.charCodeAt(0))],'dropped.jpg',{type:'image/jpeg'}));zone.dispatchEvent(new DragEvent('drop',{bubbles:true,dataTransfer:data}))},bytes)
 const result=await response;if(!result.ok())throw new Error('Real drag/drop search failed')
 await page.locator('.result-tile').first().waitFor()
 await page.locator('#ai-search').screenshot({path:'verification/final-ai-390.png'})
 const report={cart,wishlist,focusTrapped,restoredFocus,oversizeValidation:true,realDragDropStatus:result.status(),errors,scrollWidth:await page.evaluate(()=>document.documentElement.scrollWidth)}
 fs.writeFileSync('verification/final-interactions.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2))
}finally{await browser.close()}
